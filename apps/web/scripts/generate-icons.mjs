const data = {};
for (const [name, id] of Object.entries(ICONS)) {
  const icon = getIconById(id);
  const variant = icon?.variants?.normal;
  if (!variant) throw new Error(`Rune icon "${id}" (for "${name}") has no "normal" variant`);
  data[name] = {
    viewBox: variant.viewBox,
    markup: variant.markup.replace(/\r?\n/g, '').replace(/>\s+</g, '><'),
  };
}

const out = `// AUTO-GENERATED by scripts/generate-icons.mjs from runeicons-react (Apache-2.0,
// https://runeicons.com). Do not edit by hand.
export const ICON_DATA = ${JSON.stringify(data, null, 2)} as const;

export type IconName = keyof typeof ICON_DATA;
`;
const target = fileURLToPath(
  new URL('../src/components/icons/icon-data.generated.ts', import.meta.url),
);
writeFileSync(target, out);
console.warn(`Wrote ${Object.keys(data).length} icons to ${target}`);
